package.path='./?.lua;'..package.path
local g=require('shared.input.gestures')
local s=g.new()
g.begin(s,1,350,500,nil);g.move(s,1,250,500)
assert(s[1].horizontal and g.finish(s,1,180,505).swipe==-1 and next(s)==nil)
g.begin(s,1,80,500,nil);assert(g.finish(s,1,200,500).swipe==1)
g.begin(s,1,350,500,'helmet');assert(g.finish(s,1,180,500).swipe==-1)
g.begin(s,1,350,500,'helmet');assert(g.finish(s,1,345,501).tap=='helmet')
g.begin(s,1,350,500,'helmet');g.move(s,1,280,500)
assert(not g.finish(s,1,350,500).tap,'Dragging back onto a button must not activate it')
g.begin(s,1,200,200,nil);assert(not g.finish(s,1,155,200).swipe,'Short drag navigated')
g.begin(s,1,200,200,nil);assert(not g.finish(s,1,100,350).swipe,'Vertical drag navigated')
g.begin(s,1,240,155,nil);g.begin(s,2,405,340,'suit')
assert(not s[1].eligible and not s[2].eligible)
assert(g.finish(s,2,405,340).tap=='suit')
assert(not g.finish(s,1,60,155).swipe,'Multitouch must not turn into navigation')
g.begin(s,'mouse',350,500,nil);assert(g.finish(s,'mouse',100,500).swipe==-1)
assert(not g.finish(s,'missing',20,20).tap)
print('PASS gestures: swipes, tap/drag distinction, multitouch and mouse parity')
