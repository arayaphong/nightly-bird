#!/usr/bin/env python3
"""Generate two sparse, reusable night-sky layers as Rive vector paths."""
import math
from defold_rive_bird import ROOT,start_file,finish_file,draw_path,path
from defold_rive_gallery import radial,ellipse

def build():
    seed=73021
    def random():
        nonlocal seed
        seed=seed*48271%2147483647
        return seed/2147483647
    stars=[];dust=[]
    for i in range(72):
        stars.append(dict(x=random()*480,y=random()*800,radius=.45+random()*.45,
                          phase=random()*math.tau,rate=.45+random()*1.1,spark=i%15==0))
        # Preserve the existing seeded positions after removing random speeds.
        random()
    for i in range(26):
        dust.append(dict(x=random()*480,y=random()*800,radius=.6+random()*.35,
                         phase=random()*math.tau,speed=.7+random()*.55,
                         alpha=.7+random()*.18,tail=4+random()*6))
    channels={}
    for i,p in enumerate(stars):
        channels.update({f'star_{i}_x':p['x'],f'star_{i}_alpha':.6})
    for i,p in enumerate(dust):
        channels.update({f'dust_{i}_x':p['x'],f'dust_{i}_y':p['y'],
                         f'dust_{i}_angle':math.pi,f'dust_{i}_alpha':p['alpha']})
    keys={k:i for i,k in enumerate(channels)}
    f=start_file(channels,'NightSky',480,800,'NightSkyControls')
    # Rive draws the component stream back-to-front. Dust is in front of stars.
    front=f.node('wind-dust')
    for i,p in enumerate(dust):
        node=f.node(f'dust-{i}',front,p['x'],p['y'],math.pi)
        for prop,key in ((13,'x'),(14,'y'),(15,'angle'),(18,'alpha')):
            f.bind(prop,keys[f'dust_{i}_{key}'])
        draw_path(f,ellipse(p['radius'],'#ffffff'),node)
        glow=radial('dust-glow',p['radius']*3.5,'rgba(240,248,255,.45)','rgba(240,248,255,0)')
        draw_path(f,ellipse(p['radius']*3.5,'url(#dust-glow)'),node,{'dust-glow':glow})
        # Local positive x is travel direction; the faint tail trails behind.
        draw_path(f,path(f'M{-p["radius"]} 0 L{-p["tail"]} 0',
                         stroke='rgba(225,238,255,.18)',stroke_width=.45,stroke_linecap='round'),node)
    back=f.node('distant-stars')
    for i,p in enumerate(stars):
        node=f.node(f'star-{i}',back,p['x'],p['y']);f.bind(13,keys[f'star_{i}_x']);f.bind(18,keys[f'star_{i}_alpha'])
        draw_path(f,ellipse(p['radius'],'#e8efff'),node)
        if p['spark']:
            draw_path(f,path('M-2 0 L2 0 M0 -2 L0 2',stroke='rgba(220,235,255,.3)',stroke_width=.4),node)
    # Opaque black also keeps the Studio renderer's navy clear color out.
    draw_path(f,path('M0 0 H480 V800 H0 Z','#000000'),0)
    finish_file(f,'night-sky','Sky',destination='shared/scenery/night_sky/visual.riv')
    def lua(p):
        return '{'+','.join(f'{k}='+('true' if v is True else 'false' if v is False else format(v,'.17g')) for k,v in p.items())+'}'
    dest=ROOT/'shared/scenery/night_sky/layout.lua'
    dest.write_text('-- Generated by scripts/defold_rive_night_sky.py; units are 480x800, y down.\nreturn {width=480,height=800,margin=14,stars={\n'+',\n'.join(lua(p) for p in stars)+'\n},dust={\n'+',\n'.join(lua(p) for p in dust)+'\n}}\n')

if __name__=='__main__':build()
