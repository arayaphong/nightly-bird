"""Opaque vector water and a matching animated cubic surface boundary."""
import math
import xml.etree.ElementTree as ET
from defold_rive_bird import ROOT,draw_path,path

POINTS=23
STEP=24
MIN_X=-24
BASE_Y=520
WAVES=[(6,math.tau/240,.9,0),(2.4,math.tau/125,1.3,1.1)]

def sample(x):
    y=BASE_Y+sum(a*math.sin(k*x+phase) for a,k,rate,phase in WAVES)
    slope=sum(a*k*math.cos(k*x+phase) for a,k,rate,phase in WAVES)
    return y,slope

def channels():
    out={'water_alpha':0}
    for i in range(POINTS):
        y,slope=sample(MIN_X+i*STEP)
        out.update({f'water_y_{i}':y,f'water_in_{i}':math.atan2(-slope,-1),
                    f'water_out_{i}':math.atan2(slope,1),f'water_length_{i}':STEP/3*math.hypot(1,slope)})
    return out

def add_water(f,keys):
    root=f.node('water',opacity=0);f.bind(18,keys['water_alpha'])
    samples=[(MIN_X+i*STEP,*sample(MIN_X+i*STEP)) for i in range(POINTS)]
    d=f'M{samples[0][0]} {samples[0][1]}'
    for (x0,y0,m0),(x1,y1,m1) in zip(samples,samples[1:]):
        h=STEP/3;d+=f' C{x0+h} {y0+m0*h} {x1-h} {y1-m1*h} {x1} {y1}'
    vertices=[(None,keys[f'water_y_{i}']) for i in range(POINTS)]
    handles=[{84:keys[f'water_in_{i}'],85:keys[f'water_length_{i}'],
              86:keys[f'water_out_{i}'],87:keys[f'water_length_{i}']} for i in range(POINTS)]
    # Bright boundary, soft edge, then opaque body: all share identical cubics.
    for color,width in [('#a5d6e8',1.5),('rgba(105,187,220,.16)',5)]:
        draw_path(f,path(d,stroke=color,stroke_width=width,stroke_linecap='round'),root,
                  vertex_channels=vertices,vertex_handle_channels=handles)
    gradient=ET.Element('linearGradient',{'id':'water-depth','gradientUnits':'userSpaceOnUse',
                                         'x1':'0','y1':str(BASE_Y),'x2':'0','y2':'800'})
    for offset,color in [('0','#0b293b'),('.5','#071f31'),('1','#03121f')]:
        ET.SubElement(gradient,'stop',{'offset':offset,'stop-color':color})
    body=d+f' L{samples[-1][0]} 824 L{samples[0][0]} 824 Z'
    draw_path(f,path(body,'url(#water-depth)'),root,{'water-depth':gradient},
              vertex_channels=vertices+[(None,None)]*2,vertex_handle_channels=handles+[{},{}])

def write_rig():
    text=f'-- Generated by scripts/defold_rive_water.py; units are x-right/y-down.\nreturn {{points={POINTS},step={STEP},min_x={MIN_X},base_y={BASE_Y},waves={{\n'
    for a,k,rate,phase in WAVES:
        text+=f'    {{amplitude={a:.17g},k={k:.17g},rate={rate:.17g},phase={phase:.17g}}},\n'
    (ROOT/'shared/scenery/water/rig.lua').write_text(text+'}}\n')
